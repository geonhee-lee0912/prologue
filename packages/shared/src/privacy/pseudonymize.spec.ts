import { describe, expect, it } from 'vitest';
import { pseudonymize, redactContacts } from './pseudonymize';

describe('연락처 지우기와 가명처리', () => {
  it('휴대폰 번호를 하이픈·공백·점 모양 모두 지운다', () => {
    for (const phone of ['010-1234-5678', '01012345678', '010 1234 5678', '010.1234.5678']) {
      expect(redactContacts(`제 번호는 ${phone} 이에요`)).toBe('제 번호는 [연락처] 이에요');
    }
  });

  it('이메일과 주민등록번호를 지운다', () => {
    expect(redactContacts('abc@example.com 으로 보내 주세요')).toBe('[이메일] 으로 보내 주세요');
    expect(redactContacts('900101-1234567 이에요')).toBe('[주민번호] 이에요');
    expect(redactContacts('9001011234567 이에요')).toBe('[주민번호] 이에요');
  });

  it('국제전화 표기(+82)의 휴대폰 번호도 지운다', () => {
    for (const phone of ['+82 10-1234-5678', '+82-10-1234-5678', '+821012345678', '+82 (0)10-1234-5678', '82-10-1234-5678']) {
      expect(redactContacts(`제 번호는 ${phone} 이에요`)).toBe('제 번호는 [연락처] 이에요');
    }
  });

  it('국가 번호 뒤에 0 을 다시 붙인 번호(+82 10 010-…)도 번호 숫자를 남기지 않는다', () => {
    // 국제 표기를 먼저 지우면 '+82 10 010-1234' 까지만 먹고 꼬리 '-5678' 이 남는다 — 국내 꼴을 첫 판으로 돌린다
    const redacted = redactContacts('제 번호는 +82 10 010-1234-5678 이에요');
    expect(redacted).toContain('[연락처]');
    for (const digits of ['010', '1234', '5678']) expect(redacted).not.toContain(digits);
  });

  it('공백 낀 꼴에서도 국가 번호 뒤에 0 을 다시 붙인 번호(+82 10 010 - …)는 번호 숫자를 남기지 않는다', () => {
    // 공백 낀 꼴도 국제 표기를 먼저 지우면 '+82 10 010 - 1234' 까지만 먹고 꼬리 ' - 5678' 이 남는다 — 국내 꼴을 먼저 돌린다
    for (const phone of ['+82 10 010 - 1234 - 5678', '+82 - 10 - 010 - 1234 - 5678']) {
      const redacted = redactContacts(`제 번호는 ${phone} 이에요`);
      expect(redacted, phone).toContain('[연락처]');
      for (const digits of ['010', '1234', '5678']) expect(redacted, phone).not.toContain(digits);
    }
  });

  it('하이픈·점을 공백으로 감싸 쓴 휴대폰 번호도 지운다', () => {
    for (const phone of ['010 - 1234 - 5678', '011 - 234 - 5678', '010 -1234 -5678', '010- 1234- 5678', '010 . 1234 . 5678', '+82 10 - 1234 - 5678', '+82 - 10 - 1234 - 5678']) {
      expect(redactContacts(`제 번호는 ${phone} 이에요`)).toBe('제 번호는 [연락처] 이에요');
    }
  });

  it('주민등록번호는 하이픈 앞뒤에 공백이 있어도 지운다', () => {
    for (const rrn of ['901010 - 1234567', '901010- 1234567', '901010 -1234567', '901010-1234567']) {
      expect(redactContacts(`주민번호는 ${rrn} 이에요`)).toBe('주민번호는 [주민번호] 이에요');
    }
  });

  it('하이픈으로 바로 이어진 주민번호 꼴은 앞에 숫자가 더 붙어 있어도 예전처럼 지운다', () => {
    // 생년월일을 여덟 자리로 잘못 적은 경우 — 공백 없는 꼴의 탐지는 약해지면 안 된다
    expect(redactContacts('19900101-1234567')).not.toContain('1234567');
    expect(redactContacts('주민번호 12900101-1234567 입니다')).not.toContain('1234567');
  });

  it('앞 여섯 자리가 휴대폰 앞자리(010…)를 닮은 주민번호도 공백 낀 꼴에서 통째로 주민번호로 지운다', () => {
    // 2001년생은 주민번호가 01MMDD 로 시작해 010123 - 3234567 이 휴대폰 꼴(010 + 123 + 3234)과 겹친다 — 주민번호를 휴대폰보다 먼저
    for (const rrn of ['010123 - 3234567', '011225 - 3234567', '010123- 3234567', '010123 -3234567']) {
      expect(redactContacts(`주민번호는 ${rrn} 이에요`)).toBe('주민번호는 [주민번호] 이에요');
    }
  });

  it('공백 낀 번호 꼴이 앞에 있어도 뒤따르는 진짜 번호는 앞머리까지 통째로 지운다', () => {
    // 공백 낀 꼴을 먼저 지우면 진짜 번호의 앞머리를 먹고 뒤꼬리가 남는다 — 전부터 지우던 꼴을 먼저, 공백 낀 꼴은 남은 것만
    expect(redactContacts('010810 - 01012345678')).toBe('010810 - [연락처]');
    expect(redactContacts('900101 - 1900101234567')).toBe('900101 - [주민번호]');
  });

  it('값이나 연도 범위 같은 보통 숫자는 지우지 않는다', () => {
    for (const text of [
      '월급은 3,500,000원이고 보증금은 1,000만 원이에요',
      '2018-2024년에 일했고 2018 - 2024 사이에 이사했어요',
      '1982-10-12 에 태어났어요',
      '키는 182이고 몸무게는 82예요',
      '월급 범위는 3000000 - 4000000원이에요',
      '2018년 1월 1일 부터는 20180101 - 20241231 로 적어요',
    ]) {
      expect(redactContacts(text)).toBe(text);
    }
  });

  it('공백 낀 하이픈을 받아도 날짜·안내 번호·자리수가 모자란 번호는 지우지 않는다', () => {
    for (const text of ['2026 - 10 - 12 에 만나요', '1982 - 10 - 12 생이에요', '고객센터는 1588 - 1234 예요', '인증번호는 010 - 123 - 456 이에요']) {
      expect(redactContacts(text)).toBe(text);
    }
  });

  it('알려진 이름을 [이름] 으로 바꾼다', () => {
    expect(pseudonymize('저는 지은이라고 해요', { name: '지은' })).toBe('저는 [이름]이라고 해요');
  });

  it('한 글자 이름은 다른 낱말을 망가뜨릴 수 있어 바꾸지 않는다', () => {
    expect(pseudonymize('오늘 별 보러 가요', { name: '별' })).toBe('오늘 별 보러 가요');
  });

  it('식별자가 없으면 그대로 돌려준다', () => {
    const text = '주말에는 등산을 자주 해요';
    expect(pseudonymize(text, { name: null })).toBe(text);
  });
});
